"""Build the app's icon font and lib/widgets/app_icons.dart from icons.txt.

The design draws every icon from one family: Material Symbols Rounded at
Fill 1, weight 400, grade 0, optical size 24 (Figma 03 · pass 3). Flutter's
built-in Icons are the older Material Icons set, and the material_symbols_icons
package bundles three variable fonts (about 35 MB) of which Flutter's icon tree
shaker leaves the two unused styles at full size in a release build. So the app
carries a static instance of the one style, cut down to the icons it uses.

Usage (from the repository root):

    python -m pip install fonttools
    python tool/symbols/build_font.py "<path to MaterialSymbolsRounded variable font>"

The variable font is Apache-2.0, from github.com/google/material-design-icons
(variablefont/MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf) or the
lib/fonts folder of the material_symbols_icons package.
"""

import pathlib
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parents[2]
ICONS = ROOT / 'tool' / 'symbols' / 'icons.txt'
FONT_OUT = ROOT / 'assets' / 'fonts' / 'app_symbols.ttf'
DART_OUT = ROOT / 'lib' / 'widgets' / 'app_icons.dart'
FAMILY = 'AppSymbols'
AXES = {'FILL': 1, 'GRAD': 0, 'opsz': 24, 'wght': 400}

# Drawn as strokes in the design. Their filled and unfilled glyphs must be the
# same shape, or the static Fill 1 instance would draw them wrong.
LINE_ICONS = ['check', 'close', 'add', 'chevron_left', 'chevron_right']


def read_icons():
    icons = []
    for raw in ICONS.read_text(encoding='utf-8').splitlines():
        line = raw.split('#', 1)[0].strip()
        if not line:
            continue
        name, *flags = line.split()
        icons.append((name, 'rtl' in flags))
    names = [n for n, _ in icons]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        sys.exit(f'Listed twice in icons.txt: {sorted(duplicates)}')
    return icons


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(part[:1].upper() + part[1:] for part in rest)


def resolve(font, by_name, name):
    """The codepoint for an icon name.

    Most glyphs are named after their icon, but aliases are not: location_on
    is drawn by the glyph called "place". The font's ligature table knows every
    name, so ask it when the glyph name does not match.
    """
    if name in by_name:
        return by_name[name]
    cmap = font.getBestCmap()
    sequence = [cmap.get(ord(c)) for c in name]
    if None in sequence:
        return None
    for lookup in font['GSUB'].table.LookupList.Lookup:
        for table in lookup.SubTable:
            if lookup.LookupType == 7:
                table = table.ExtSubTable
            for ligature in getattr(table, 'ligatures', {}).get(sequence[0], []):
                if ligature.Component == sequence[1:]:
                    return by_name.get(ligature.LigGlyph)
    return None


def outlines(font, name):
    glyph = font['glyf'][name]
    glyph.expand(font['glyf'])
    coords, ends, flags = glyph.getCoordinates(font['glyf'])
    return [tuple(round(v) for v in p) for p in coords], list(ends)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    source = TTFont(sys.argv[1])
    by_name = {}
    for codepoint, glyph in source.getBestCmap().items():
        by_name.setdefault(glyph, codepoint)

    icons = read_icons()
    codepoints = {n: resolve(source, by_name, n) for n, _ in icons}
    missing = [n for n, cp in codepoints.items() if cp is None]
    if missing:
        sys.exit(f'Not in Material Symbols Rounded: {missing}')
    glyph_of = {n: source.getBestCmap()[cp] for n, cp in codepoints.items()}

    # Cut the variable font down first: instancing 4 000 glyphs is slow.
    options = subset.Options()
    options.layout_features = []
    options.hinting = False
    options.notdef_outline = True
    options.name_IDs = ['*']
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[32, *codepoints.values()])
    subsetter.subset(source)

    unfilled = instancer.instantiateVariableFont(source, {**AXES, 'FILL': 0})
    source = TTFont(sys.argv[1])
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[32, *codepoints.values()])
    subsetter.subset(source)
    filled = instancer.instantiateVariableFont(source, AXES)

    for name in LINE_ICONS:
        glyph = glyph_of[name]
        if outlines(filled, glyph) != outlines(unfilled, glyph):
            sys.exit(f'"{name}" differs between Fill 0 and Fill 1; '
                     'the line icons need their own instance.')

    FONT_OUT.parent.mkdir(parents=True, exist_ok=True)
    filled.save(FONT_OUT)

    lines = [
        '// GENERATED by tool/symbols/build_font.py from tool/symbols/icons.txt.',
        '// Do not edit by hand: add the name to icons.txt and run the script.',
        '',
        "import 'package:flutter/widgets.dart';",
        '',
        "/// The app's one icon family: Material Symbols Rounded at Fill 1, weight",
        '/// 400, grade 0, optical size 24 — the filled set every REPLIT screen draws',
        '/// from (Figma 03 · pass 3). check, close, add and the chevrons are drawn',
        '/// as 2 px strokes, as the design keeps them.',
        '///',
        '/// The glyphs live in assets/fonts/app_symbols.ttf, a static instance of',
        '/// the variable font cut down to the names in tool/symbols/icons.txt.',
        '@staticIconProvider',
        'abstract final class AppIcons {',
        "  static const String _family = '" + FAMILY + "';",
        '',
    ]
    for name, rtl in sorted(icons):
        args = f'0x{codepoints[name]:04x}, fontFamily: _family'
        if rtl:
            args += ', matchTextDirection: true'
        if lines[-1]:
            lines.append('')
        lines.append(f'  /// Material Symbols "{name}".')
        line = f'  static const IconData {camel(name)} = IconData({args});'
        if len(line) > 80:
            # The shape `dart format` gives a call too long for one line.
            line = (f'  static const IconData {camel(name)} = IconData(\n    ' +
                    ',\n    '.join(args.split(', ')) + ',\n  );')
        lines.append(line)
    lines.append('}')
    DART_OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')

    print(f'{len(icons)} icons, {FONT_OUT.stat().st_size} bytes -> '
          f'{FONT_OUT.relative_to(ROOT)}, {DART_OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
